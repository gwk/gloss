# Generate small shell scripts and selected equivalent zsh aliases from a text file.

import os.path
import re
import subprocess
import sys


skip_re = re.compile(r'\s*(#.*)?$')
line_re = re.compile(r'(\S+)(\s+@alias)?:\s+(.+?)\s*(?:#.*)?$')
alias_args_re = re.compile(r'(?:^|\s)"\$@"\s*$')
positional_param_re = re.compile(r'\$(?:[@*]|[0-9]+)')

if len(sys.argv) not in (3, 4):
  sys.exit(f'usage: {sys.argv[0]} INPUT_PATH OUT_DIR [ALIASES_PATH]')

input_path, out_dir = sys.argv[1:3]
aliases_path = sys.argv[3] if len(sys.argv) == 4 else None

print('gen-commands:', input_path, out_dir, file=sys.stderr)

fmt = '''\
# Copyright 2009-2016 George King. Permission to use this file is granted in license-gloss.txt.

# this file was generated by gen-commands.py from {}
set -e -o pipefail
{}
'''

aliases: list[tuple[str, str]] = []

with open(input_path) as input_f:
  for line_num, line in enumerate(input_f, 1):
    line = line.rstrip('\n')
    if skip_re.fullmatch(line):
      continue
    m = line_re.fullmatch(line)
    if not m:
      sys.exit(f'{input_path}:{line_num}: bad line: {line.rstrip()}')
    name = m.group(1)
    make_alias = m.group(2) is not None
    body = m.group(3).strip()
    bin_path = os.path.join(out_dir, name)
    with open(bin_path, 'w') as bin_f:
      bin_f.write(fmt.format(input_path, body))
    subprocess.check_call(['chmod', '+x', bin_path])

    if make_alias:
      args_match = alias_args_re.search(body)
      if not args_match:
        sys.exit(f'{input_path}:{line_num}: @alias body must end with "$@": {body}')
      alias_body = body[:args_match.start()].rstrip()
      if positional_param_re.search(alias_body):
        sys.exit(f'{input_path}:{line_num}: @alias body has another positional parameter: {body}')
      aliases.append((name, alias_body))

if aliases_path is not None:
  with open(aliases_path, 'w') as aliases_f:
    print(f'# Generated by gen-commands.py from {input_path}.', file=aliases_f)
    for name, body in aliases:
      escaped_body = body.replace("'", "'\\''")
      print(f"alias {name}='{escaped_body}'", file=aliases_f)
